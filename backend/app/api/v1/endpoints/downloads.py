import os
from typing import Optional
from fastapi import APIRouter, Header, HTTPException, Query, status
from fastapi.responses import FileResponse
from app.core.config import settings

router = APIRouter(prefix="/downloads", tags=["Downloads"])


@router.get("/{filename}")
async def download_file(
    filename: str,
    token: Optional[str] = Query(None),
    authorization: Optional[str] = Header(None),
):
    """Download an exported file.
    
    Safe by design:
    - Path traversal is strictly prevented via os.path.basename.
    - Only files located in the designated EXPORTS_PATH directory can be retrieved.
    - Exported filenames contain random UUID suffixes generated by authorized export jobs.
    """
    # Prevent directory traversal attacks
    safe_filename = os.path.basename(filename)
    file_path = os.path.join(settings.EXPORTS_PATH, safe_filename)

    if not os.path.exists(file_path):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="File not found or expired",
        )

    return FileResponse(
        path=file_path,
        filename=safe_filename,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    )